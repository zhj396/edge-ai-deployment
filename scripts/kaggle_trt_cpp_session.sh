#!/bin/bash
# =============================================================================
# kaggle_trt_cpp_session.sh — stage-wise TensorRT C++ (trt_cpp) session driver
# =============================================================================
# Drives the trt_cpp measurement session on a GPU box (the validated target is
# a Kaggle Tesla T4) as self-contained stages. Every stage invocation sets up
# its own environment and runs from the repo root, so a notebook cell
#
#     !bash scripts/kaggle_trt_cpp_session.sh <stage>
#
# and a fresh terminal running the same line behave identically — no sourcing,
# no cross-cell env exports.
#
# Stages (run in order):
#   deps         pip overlays (requirements-kaggle.txt then requirements-tensorrt.txt)
#                + Release artifacts (models/yolov8s.pt, coco12-val.zip) + the
#                CUDA loader env file (env_cuda.sh, see below)
#   build        canonical FP32 ONNX export + FP32/FP16/INT8-QDQ engines
#                (static batch=1, the Turing route)
#   trt-cpp      TensorRT 10.16.1 tarball subset (include/ + lib/) via
#                scripts/trt_cpp_setup.sh + the _trt_cpp pybind11 module build
#   consistency  4 runs vs the canonical FP32 ONNX: trt_cpp FP32 (strict,
#                pinned), trt_cpp FP16 (auto-loose), trt_cpp INT8 tensor +
#                detection (auto-loose)
#   benchmark    Python tensorrt* + trt_cpp* rows in one call (the two engine
#                families are serialized with release() inside the run);
#                canonical protocol --warmup 10 --runs 25. Run twice and keep
#                the second pass (cold-start GPU contention on a shared T4
#                pollutes the first — the recorded-runs protocol)
#   archive      model sha256 inventory + a results tarball into the working
#                dir (download before the session dies; run artifacts are not
#                committed)
#
# The stage commands themselves are the canonical form documented in
# docs/TENSORRT.md; this script only sequences them and pins the environment.
#
# Why env_cuda.sh: onnxruntime-gpu's wheel does not bundle the CUDA runtime —
# the CUDA-12 libraries (libcublas.so.12, libcudnn.so.9, ...) come with the
# pip nvidia-* wheels that the preinstalled CUDA torch build pulls in, and
# those directories are not on the system loader path. Every Python stage
# therefore prepends the pip nvidia lib dirs to LD_LIBRARY_PATH (generated
# once into env_cuda.sh by `deps` and re-read by each stage), so the CUDA
# execution provider loads instead of silently falling back to CPU.
#
# Models and run artifacts stay outside the repo (models/ and results*/ are
# git-ignored); the archive stage packages them for local download.
# =============================================================================
set -eo pipefail

STAGE=${1:-}
if [ -z "${STAGE}" ]; then
    echo "Usage: bash scripts/kaggle_trt_cpp_session.sh <deps|build|trt-cpp|consistency|benchmark|archive>"
    exit 1
fi

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${REPO_ROOT}"

RESULTS_DIR="results_on_kaggle"
ENV_FILE="/kaggle/working/env_cuda.sh"
TENSORRT_ROOT_DIR="${TENSORRT_INSTALL_DIR:-/kaggle/working}/TensorRT-10.16.1.11"
mkdir -p "${RESULTS_DIR}" models results

log() { tee "${RESULTS_DIR}/$1"; }   # stage logs land beside the run artifacts

# Re-read the loader env generated by `deps` (no-op when the file is absent —
# e.g. a box whose system CUDA already satisfies onnxruntime-gpu).
if [ -f "${ENV_FILE}" ]; then
    # shellcheck disable=SC1090
    source "${ENV_FILE}"
fi

# The built _trt_cpp module links libnvinfer.so.10 — every stage that imports
# it (consistency / benchmark resolve the module lazily on the first
# trt_cpp: forward) needs the tarball's lib dir on the loader path too.
TRT_LIB="${TENSORRT_ROOT_DIR}/lib"
if [ -d "${TRT_LIB}" ]; then
    export LD_LIBRARY_PATH="${TRT_LIB}:${LD_LIBRARY_PATH:-}"
fi

case "${STAGE}" in
deps)
    echo "=== [deps] pip overlays ==="
    pip install -r requirements-kaggle.txt
    pip install --extra-index-url https://pypi.nvidia.com -r requirements-tensorrt.txt

    echo "=== [deps] Release artifacts ==="
    if [ ! -f models/yolov8s.pt ]; then
        curl -sL -o models/yolov8s.pt \
            "https://github.com/zhj396/edge-ai-deployment/releases/download/v0.1.0/yolov8s.pt"
    fi
    if [ ! -d data/images/val ]; then
        curl -sL -o /tmp/coco12-val.zip \
            "https://github.com/zhj396/edge-ai-deployment/releases/download/v0.1.0/coco12-val.zip"
        unzip -q -o /tmp/coco12-val.zip -d "${REPO_ROOT}/data"
        rm -f /tmp/coco12-val.zip
    fi

    echo "=== [deps] CUDA loader env (env_cuda.sh) ==="
    # The pip nvidia-* wheels' lib dirs, joined into one LD_LIBRARY_PATH line.
    # /usr/local/cuda/lib64 is appended last so the system toolkit stays
    # reachable for anything the pip wheels do not ship.
    NVIDIA_LIBS="$(ls -d /usr/local/lib/python3.13/dist-packages/nvidia/*/lib 2>/dev/null | tr '\n' ':' | sed 's/:$//')"
    if [ -z "${NVIDIA_LIBS}" ]; then
        echo "No pip nvidia lib dirs found — writing an empty env file." \
            "(If onnxruntime-gpu later fails to load libcublas.so.12, locate" \
            "the CUDA libs on this box and extend ENV_FILE.)"
    fi
    echo "export LD_LIBRARY_PATH=${NVIDIA_LIBS}:/usr/local/cuda/lib64:${LD_LIBRARY_PATH:-}" \
        > "${ENV_FILE}"
    echo "Wrote ${ENV_FILE}:"
    cat "${ENV_FILE}"

    echo "=== [deps] versions snapshot ==="
    {
        nvidia-smi
        python -c "import onnxruntime, torch; print('onnxruntime', onnxruntime.__version__, '| torch', torch.__version__, '| cuda available', torch.cuda.is_available())"
        python -c "import tensorrt; print('tensorrt', tensorrt.__version__)" 2>/dev/null \
            || echo "tensorrt wheel absent (install stage ran requirements-tensorrt.txt?)"
        python -c "import glob, sys; sys.path.insert(0, '.'); import utils" 2>/dev/null || true
    } > "${RESULTS_DIR}/env.txt" 2>&1
    cat "${RESULTS_DIR}/env.txt"
    ;;

build)
    echo "=== [build] canonical FP32 ONNX (the consistency reference) ==="
    if [ ! -f models/yolov8s_fp32.onnx ]; then
        python main.py export --model models/yolov8s.pt 2>&1 | log 00b_export_fp32.log
    fi

    echo "=== [build] engines: FP32 / FP16 / INT8-QDQ (static, Turing route) ==="
    # The INT8 build takes the default QDQ path (head-excluded ORT quantization,
    # no TRT calibrator) — the same construction the recorded Python-path runs used.
    for prec in fp32 fp16 int8; do
        python main.py tensorrt build --model models/yolov8s.pt --static \
            --precision "${prec}" --output "models/yolov8s_${prec}.engine" \
            2>&1 | log "01_build_${prec}.log"
    done
    ls -lh models/*.engine
    ;;

trt-cpp)
    echo "=== [trt-cpp] C++ deps (apt OpenCV dev + TRT tarball subset) ==="
    # trt_cpp_setup.sh must be SOURCED for its exports, but this stage is a
    # one-shot shell: run the download/extract through it, then pass
    # TENSORRT_ROOT to cmake explicitly (the env does not persist anyway).
    (source scripts/trt_cpp_setup.sh) 2>&1 | log 02a_setup.log

    echo "=== [trt-cpp] cmake configure + _trt_cpp build ==="
    if [ -f cpp/build/CMakeCache.txt ] && ! grep -q "BUILD_TRT_CPP:BOOL=ON" cpp/build/CMakeCache.txt; then
        rm -rf cpp/build   # stale configure without the flag would skip the tensorrt subdir
    fi
    cmake -S cpp -B cpp/build -DBUILD_TRT_CPP=ON \
        -DTENSORRT_ROOT="${TENSORRT_ROOT_DIR}" 2>&1 | log 02b_cmake_configure.log
    cmake --build cpp/build --target _trt_cpp 2>&1 | log 02c_cmake_build.log

    echo "=== [trt-cpp] module smoke ==="
    LD_LIBRARY_PATH="${TENSORRT_ROOT_DIR}/lib:${LD_LIBRARY_PATH:-}" \
        python -c "from src import trt_cpp_available; print('trt_cpp_available:', trt_cpp_available())" \
        2>&1 | log 02d_smoke.log
    ;;

consistency)
    # The canonical FP32 ONNX is the reference on the left of every pair.
    # The FP32-engine run pins the strict pair explicitly: the .engine suffix
    # routes the auto-selector to loose (docs/TENSORRT.md tolerance section).
    # tensorrt: and trt_cpp: never share one run — the two engine families
    # hold different CUDA context flavors and are not co-constructed here.
    echo "=== [consistency] trt_cpp FP32 (strict, pinned) ==="
    python main.py consistency \
        --model1 models/yolov8s_fp32.onnx --model2 trt_cpp:models/yolov8s_fp32.engine \
        --atol 1e-4 --rtol 1e-3 --mode tensor \
        --report-path results/consistency_trtcpp_fp32.json \
        2>&1 | log 03a_trtcpp_fp32_strict.log

    echo "=== [consistency] trt_cpp FP16 (auto-loose, tensor mode) ==="
    python main.py consistency \
        --model1 models/yolov8s_fp32.onnx --model2 trt_cpp:models/yolov8s_fp16.engine \
        --mode tensor \
        --report-path results/consistency_trtcpp_fp16.json \
        2>&1 | log 03b_trtcpp_fp16.log

    echo "=== [consistency] trt_cpp INT8 (auto-loose, tensor mode) ==="
    python main.py consistency \
        --model1 models/yolov8s_fp32.onnx --model2 trt_cpp:models/yolov8s_int8.engine \
        --mode tensor \
        --report-path results/consistency_trtcpp_int8_tensor.json \
        2>&1 | log 03c_trtcpp_int8_tensor.log

    echo "=== [consistency] trt_cpp INT8 (detection mode, per-image gates) ==="
    python main.py consistency \
        --model1 models/yolov8s_fp32.onnx --model2 trt_cpp:models/yolov8s_int8.engine \
        --mode detection \
        --report-path results/consistency_trtcpp_int8_detection.json \
        2>&1 | log 03d_trtcpp_int8_detection.log
    ;;

benchmark)
    echo "=== [benchmark] pass 1 (cold — recorded-run protocol discards it) ==="
    python main.py benchmark \
        --model tensorrt:models/yolov8s_fp32.engine \
        --model trt_cpp:models/yolov8s_fp32.engine \
        --model tensorrt_fp16:models/yolov8s_fp16.engine \
        --model trt_cpp_fp16:models/yolov8s_fp16.engine \
        --model tensorrt_int8:models/yolov8s_int8.engine \
        --model trt_cpp_int8:models/yolov8s_int8.engine \
        --imgs-input data --batch-size 1 --warmup 10 --runs 25 --device cpu \
        2>&1 | log 04a_benchmark_pass1.log

    echo "=== [benchmark] pass 2 (the recorded pass) ==="
    python main.py benchmark \
        --model tensorrt:models/yolov8s_fp32.engine \
        --model trt_cpp:models/yolov8s_fp32.engine \
        --model tensorrt_fp16:models/yolov8s_fp16.engine \
        --model trt_cpp_fp16:models/yolov8s_fp16.engine \
        --model tensorrt_int8:models/yolov8s_int8.engine \
        --model trt_cpp_int8:models/yolov8s_int8.engine \
        --imgs-input data --batch-size 1 --warmup 10 --runs 25 --device cpu \
        2>&1 | log 04b_benchmark_pass2.log

    echo "=== [benchmark] mAP pass (native evaluator, full val split) ==="
    python main.py benchmark \
        --model tensorrt:models/yolov8s_fp32.engine \
        --model trt_cpp:models/yolov8s_fp32.engine \
        --model tensorrt_fp16:models/yolov8s_fp16.engine \
        --model trt_cpp_fp16:models/yolov8s_fp16.engine \
        --model tensorrt_int8:models/yolov8s_int8.engine \
        --model trt_cpp_int8:models/yolov8s_int8.engine \
        --imgs-input data --batch-size 1 --device cpu \
        --validation --conf-threshold 0.001 --iou-threshold 0.7 \
        2>&1 | log 04c_benchmark_map.log
    ;;

archive)
    echo "=== [archive] model inventory ==="
    sha256sum models/*.engine models/*.onnx models/*.pt > "${RESULTS_DIR}/05a_models_sha256.log" 2>&1 || true
    cat "${RESULTS_DIR}/05a_models_sha256.log"

    echo "=== [archive] packaging results (download before the session ends) ==="
    ARCHIVE="/tmp/trt_cpp_kaggle_v1.tar.gz"
    tar czf "${ARCHIVE}" "${RESULTS_DIR}" results
    cp "${ARCHIVE}" "${REPO_ROOT}/"
    ls -lh "${REPO_ROOT}/"trt_cpp_kaggle_v1.tar.gz
    echo "Download the tarball now — /tmp and the notebook session do not survive"
    echo "past shutdown; nothing under results*/ is committed to the repo."
    ;;

*)
    echo "Unknown stage: ${STAGE}"
    echo "Usage: bash scripts/kaggle_trt_cpp_session.sh <deps|build|trt-cpp|consistency|benchmark|archive>"
    exit 1
    ;;
esac
