def validate_consistency(
    model1: str,
    model2: str,
    imgs_input: Union[str, Path],
    mode: Literal["tensor", "detection"] = "tensor",
    max_images: int = 100,
    img_sizes: Optional[List[int]] = None,
    batch_sizes: Optional[List[int]] = None,
    resnet50: Optional[Path] = None,
    device: str = "cpu",
    conf_thres: float = 0.25,
    iou_thres: float = 0.45,
    atol: float = 1e-4,
    rtol: float = 1e-3,
    cosine_similarity_thresh: float = 0.995,
    mean_diff_thresh: float = 0.01,
    p99_thresh: float = 0.05,
    det_iou_thresh: float = 0.5,
    mean_iou_thresh: float = 0.92,
    class_match_thresh: float = 0.98,
    score_diff_thresh: float = 0.08,
    count_diff_thresh: int = 3,
    recall_match_thresh: float = 0.97,
    num_workers: int = 4,
    seed: int = 42,
    copy_failed_samples: bool = True,
    report_path: Optional[Union[str, Path]] = None,
) -> Dict:
    """Run consistency validation between two models.

    Use cases
    ---------
    1. PyTorch (.pt) vs ONNX FP32 — ``mode="tensor"``
    2. ONNX FP32 vs ONNX INT8 — ``mode="detection"``
    """
    np.random.seed(seed)
    torch.manual_seed(seed)

    logger.info("=" * 60)
    logger.info("YOLOv8s Consistency Validation")
    logger.info("Model1: %s", Path(model1).name)
    logger.info("Model2: %s", Path(model2).name)
    logger.info("Mode: %s | Device: %s", mode, device)

    model_obj1 = ModelWrapper(model1, device)
    model_obj2 = ModelWrapper(model2, device)

    # Device provenance for an OpenVINO side: requested vs actual (a GPU
    # request that no enumerated device can serve resolves to the engine's
    # warned CPU fallback, so the report states what actually ran).
    openvino_provenance: Dict[str, Dict] = {}
    for obj in (model_obj1, model_obj2):
        if obj.type == "openvino" and getattr(obj, "openvino_device", None):
            openvino_provenance[obj.path] = obj.openvino_device

    data_yaml = Path(imgs_input) / "data.yaml"
    if not data_yaml.exists():
        raise FileNotFoundError(f"data.yaml not found: {data_yaml}")

    # Class count for the detection-mode post_process call: explicit nc keeps
    # the layout resolution exact (the same contract the engine _run_batch
    # bodies follow).
    try:
        with open(data_yaml, "r", encoding="utf-8") as f:
            _cfg = yaml.safe_load(f)
        _names = _cfg.get("names") if isinstance(_cfg, dict) else None
        num_classes = (
            len(_names) if isinstance(_names, (list, dict)) and len(_names) > 0
            else None
        )
    except (OSError, yaml.YAMLError):
        num_classes = None
    if num_classes is None:
        logger.info(
            "data.yaml carries no resolvable 'names' field; detection-mode "
            "post_process falls back to the layout heuristic"
        )

    # Imported lazily so that `from src.consistency import compare_tensors` (the
    # test path) doesn't pull in sampler → torchvision / imagehash / yaml.
    from .sampler import CalibrationSampler

    sampler = CalibrationSampler(
        data_yaml=data_yaml,
        calibration_size=max_images,
        local_weights=resnet50,
        device=device,
    )
    imgs = sampler.sample()
    if not imgs:
        raise RuntimeError("No valid images found")

    logger.info("Loaded %d images", len(imgs))

    img_sizes = img_sizes or [640]
    batch_sizes = batch_sizes or [1, 4, 8, 16]

    results: List[Dict] = []
    # Resolve report_path: CLI passes the timestamped path; direct library
    # callers that omit it get the unsuffixed fixed path.
    if report_path is None:
        report_path = "results/consistency_report.json"
    report_path = Path(report_path)
    # Derive fail_dir from report_path so the failed-sample directory belongs
    # to the same run as the report. Done by name-replace so the suffix
    # mirrors the report filename 1:1 regardless of timestamp
    # format: ``consistency_report_<TS>.json`` → ``consistency_failed_<TS>``
    # (stem, i.e. dir name); the default ``consistency_report.json`` →
    # ``consistency_failed``. A library caller passing a custom
    # ``report_path`` (e.g. ``foo.json``) gets a matching ``foo`` dir.
    fail_name = report_path.name.replace("consistency_report", "consistency_failed")
    fail_dir = report_path.with_name(Path(fail_name).stem)
    if copy_failed_samples:
        fail_dir.mkdir(parents=True, exist_ok=True)

    try:
        for imgsz in img_sizes:
            for bs in batch_sizes:
                logger.info("\nTest config: imgsz=%d, batch=%d", imgsz, bs)
                batch_results: List[Dict] = []
                failures = 0
                detection_failures = 0

                iterator = range(0, len(imgs), bs)
                for i in tqdm(iterator, desc=f"bs={bs}"):
                    batch_paths = imgs[i : i + bs]
                    try:
                        pre = preprocess_imgs(
                            batch_paths, imgsz=imgsz,
                            device=device, num_workers=num_workers,
                        )
                        x = pre["images"]

                        # paths/imgsz only matter for the ort_cpp backend (it
                        # re-preprocesses from the image files — the full-pipeline
                        # comparison); the other backends ignore them.
                        out1 = model_obj1.forward(x, paths=pre["paths"], imgsz=imgsz)
                        out2 = model_obj2.forward(x, paths=pre["paths"], imgsz=imgsz)

                        stats = compare_tensors(
                            out1, out2, atol, rtol,
                            cosine_similarity_thresh, mean_diff_thresh,
                            p99_thresh, mode,
                            # Use the deployed conf threshold as the conf-cliff for
                            # per-side surviving-box counts (tensor mode).
                            conf_cliff=conf_thres,
                            # Explicit nc (resolved from data.yaml above) keeps
                            # the class-channel split and the cliff gate exact
                            # on non-validated head layouts too — the same
                            # contract the post_process calls follow.
                            nc=num_classes,
                        )
                        stats.update({
                            "imgsz": imgsz,
                            # Actual batch fed to both models: preprocess_imgs drops
                            # unreadable images, so this can be < len(batch_paths).
                            "batch_size": len(pre["paths"]),
                            "mode": mode,
                        })

                        if mode == "detection":
                            dets1 = post_process(
                                out1, orig_shapes=pre["orig_shapes"],
                                conf_thres=conf_thres, iou_thres=iou_thres,
                                imgsz=imgsz,
                                ratios=pre.get("ratios"), pads=pre.get("pads"),
                                nc=num_classes,
                            )
                            dets2 = post_process(
                                out2, orig_shapes=pre["orig_shapes"],
                                conf_thres=conf_thres, iou_thres=iou_thres,
                                imgsz=imgsz,
                                ratios=pre.get("ratios"), pads=pre.get("pads"),
                                nc=num_classes,
                            )

                            per_image = []
                            for d1, d2, p in zip(dets1, dets2, pre["paths"]):
                                ds = compare_detections(
                                    d1, d2, det_iou_thresh, mean_iou_thresh,
                                    class_match_thresh, score_diff_thresh,
                                    count_diff_thresh, recall_match_thresh,
                                )
                                ds["image_path"] = str(p)
                                per_image.append(ds)

                            if per_image:
                                det_summary = {
                                    "det_passed": all(ds["passed"] for ds in per_image),
                                    "det_mean_iou": float(np.mean(
                                        [ds["mean_iou"] for ds in per_image]
                                    )),
                                    "det_class_match_rate": float(np.mean(
                                        [ds["class_match_rate"] for ds in per_image]
                                    )),
                                    "det_score_diff_mean": float(np.mean(
                                        [ds["score_diff_mean"] for ds in per_image]
                                    )),
                                    "det_count_diff_mean": float(np.mean(
                                        [ds["count_diff"] for ds in per_image]
                                    )),
                                }
                                stats.update(det_summary)
                                stats["per_image_detection"] = per_image

                                # In detection mode the per-image IoU/class/score gates
                                # decide pass/fail; the tensor verdict (cosine /
                                # mean_diff / p99 on the raw output) is informational.
                                stats["tensor_gate_passed"] = bool(stats.get("passed", False))
                                stats["passed"] = bool(det_summary["det_passed"])
                                stats["status"] = "PASS" if stats["passed"] else "FAIL"

                                if not det_summary["det_passed"]:
                                    logger.warning(
                                        "Detection comparison failed (batch_size=%d)",
                                        len(pre["paths"]),
                                    )
                                    for ds in (d for d in per_image if not d["passed"]):
                                        logger.warning(
                                            "%s | IoU=%.4f | Class=%.3f | "
                                            "ScoreDiff=%.4f | CountDiff=%d",
                                            Path(ds["image_path"]).name,
                                            ds["mean_iou"], ds["class_match_rate"],
                                            ds["score_diff_mean"], ds["count_diff"],
                                        )

                        batch_results.append(stats)

                        if not stats["passed"]:
                            failures += 1
                            # Detection-level verdict — present only in tensor mode
                            # (compare_tensors sets ``detection_consistent`` when the
                            # conf-cliff gate ran).
                            det_c = stats.get("detection_consistent")
                            if det_c is False:
                                detection_failures += 1
                            if "above_cliff_1" in stats:
                                cliff = (
                                    f" | above_cliff {stats.get('above_cliff_1')}→"
                                    f"{stats.get('above_cliff_2')} "
                                    f"(promoted={stats.get('cliff_promoted_1to2')}, "
                                    f"demoted={stats.get('cliff_demoted_1to2')})"
                                )
                            else:
                                cliff = ""
                            if det_c is True:
                                det_seg = " | detection: CONSISTENT (cliff clean)"
                            elif det_c is False:
                                det_seg = " | detection: INCONSISTENT (cliff flip)"
                            else:
                                det_seg = ""
                            logger.warning(
                                "Inconsistent | max_diff=%.6f | cos=%.6f | "
                                "cls_max_diff=%s%s%s",
                                stats.get("max_diff"),
                                stats.get("cosine_similarity"),
                                ("%.2e" % stats["cls_max_diff"])
                                if "cls_max_diff" in stats else "n/a",
                                cliff,
                                det_seg,
                            )
                            if copy_failed_samples:
                                for p in pre["paths"]:
                                    logger.warning("Failed image: %s", p)
                                    try:
                                        dst = fail_dir / f"{uuid.uuid4()}_{Path(p).name}"
                                        shutil.copy(p, dst)
                                    except Exception:
                                        logger.exception("Failed to copy image")

                    except Exception:
                        failures += 1
                        logger.exception("Batch processing failed")

                # Batches attempted for this config. Exception batches count toward
                # ``failures`` but are not appended to ``batch_results``.
                n_attempted = max(1, (len(imgs) + bs - 1) // bs) if imgs else 1

                summary: Dict = {
                    "imgsz": imgsz,
                    "batch_size": bs,
                    "total_batches": n_attempted,
                    "failures": failures,
                    "fail_rate": failures / n_attempted,
                    # Conf-cliff (detection-level) failure count — tensor mode only;
                    # 0 in detection mode.
                    "detection_failures": detection_failures,
                    "detection_fail_rate": detection_failures / n_attempted,
                    "overall_status": "PASS" if failures == 0 else "FAIL",
                    "detailed_results": batch_results,
                }

                for k in ("max_diff", "mean_diff", "p95", "p99",
                          "std_diff", "cosine_similarity",
                          "cls_max_diff", "cls_mean_diff", "cls_p99", "cls_cos",
                          "above_cliff_1", "above_cliff_2",
                          "cliff_promoted_1to2", "cliff_demoted_1to2"):
                    vals = [s.get(k) for s in batch_results if k in s]
                    if vals:
                        summary[f"{k}_mean"] = float(np.mean(vals))

                results.append(summary)
                # Write incrementally so a crash mid-run keeps partial results.
                atomic_json_dump({"results": results, "mode": mode}, report_path)

                logger.info(
                    "fail_rate=%.2f%% | detection_fail_rate=%.2f%%",
                    summary["fail_rate"] * 100, summary["detection_fail_rate"] * 100,
                )

    finally:
        # A tensorrt: wrapper's .engine is deserialized lazily on the first
        # forward; release both wrappers so its stream, device buffers, and
        # primary context do not outlive the run (a no-op for the other
        # backends and for wrappers that never ran a forward).
        model_obj1.release()
        model_obj2.release()

    overall_pass = all(r["overall_status"] == "PASS" for r in results)
    final_result = {"results": results, "overall_pass": overall_pass, "mode": mode}
    if openvino_provenance:
        final_result["openvino_devices"] = openvino_provenance
    # Final dump supersedes the last incremental write with the complete
    # record, adding ``overall_pass`` — the incremental writes omit it
    # because the verdict only exists once every (imgsz, batch) config has
    # run. A report without ``overall_pass`` is a crash-left partial, not
    # a verdict.
    atomic_json_dump(final_result, report_path)

    logger.info("=" * 60)
    logger.info("Consistency validation %s", "PASS" if overall_pass else "FAIL")
    gc.collect()
    return final_result
