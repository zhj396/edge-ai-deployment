def get_ort_session(onnx_path: str, device: str) -> ort.InferenceSession:
    """Create an ORT ``InferenceSession`` with the project's shared provider selection
    (``select_providers``), so consistency runs use the same CUDA EP configuration
    as ``infer``."""
    providers = select_providers(device)
    logger.info("ONNX Runtime providers: %s (device=%s)", providers, device)

    session = ort.InferenceSession(onnx_path, providers=providers)
    active = session.get_providers()

    if device == "cuda" and "CUDAExecutionProvider" not in active:
        logger.warning("CUDAExecutionProvider requested but not active; fell back to %s", active)
    return session


def pt_forward(model: YOLO, x: torch.Tensor) -> np.ndarray:
    """Run a PyTorch YOLO forward pass and return numpy output."""
    with torch.no_grad():
        out = model.model(x)
        if isinstance(out, (list, tuple)):
            out = out[0]
        assert isinstance(out, torch.Tensor), (
            f"PyTorch output is not a Tensor: {type(out)}"
        )
        return out.detach().cpu().numpy()


def ort_forward(
    session: ort.InferenceSession, x: torch.Tensor, device: str
) -> np.ndarray:
    """Run an ORT forward pass and return numpy output (CUDA via DLPack)."""
    if device == "cuda" and torch.cuda.is_available():
        try:
            # ``to_dlpack`` requires contiguous memory; ``.contiguous()`` is a no-op for
            # the already-contiguous tensors ``preprocess_imgs`` returns. Mirrors the
            # CUDA branch of ``YOLOv8Engine._forward``.
            ort_input = ort.OrtValue.from_dlpack(to_dlpack(x.contiguous()))
        except Exception as e:
            logger.warning("DLPack conversion failed, falling back to CPU: %s", e)
            ort_input = x.detach().cpu().numpy().astype(np.float32)
    else:
        ort_input = x.detach().cpu().numpy().astype(np.float32)

    input_name = session.get_inputs()[0].name
    if isinstance(ort_input, ort.OrtValue):
        # The input tensor is produced asynchronously on the torch stream
        # (``preprocess_imgs``: pinned H2D copy + in-place normalization),
        # while ORT executes on its own stream and reads the DLPack buffer
        # without waiting for the producer. Synchronize the producing
        # stream before handing the buffer to ORT.
        torch.cuda.current_stream().synchronize()
    return session.run(None, {input_name: ort_input})[0]


def trt_forward_capped(engine, x_np: np.ndarray) -> np.ndarray:
    """Run one TensorRT forward, sub-looping when the batch exceeds the
    engine's per-forward bound.

    ``TensorRTEngine._forward`` raises for a batch above ``max_batch``
    (the serialized optimization-profile max), and the consistency harness
    feeds whole preprocessed batches straight through, so the count is
    capped via ``_effective_batch`` and the chunks' raw outputs are
    concatenated in input order (the head layout ``[bs, 4+nc, N]`` stacks
    on axis 0). ``raw_forward`` returns a view of the engine's reused host
    output buffer, so each chunk is copied before the next forward
    overwrites that buffer.
    """
    bs = int(x_np.shape[0])
    eff = engine._effective_batch(bs)
    if eff >= bs:
        return engine.raw_forward(x_np)
    outs = [
        np.array(engine.raw_forward(x_np[i: i + eff]))
        for i in range(0, bs, eff)
    ]
    return np.concatenate(outs, axis=0)


