# Unified model wrapper
# ---------------------------------------------------------------------------
class ModelWrapper:
    """Unified interface for PyTorch, ONNX, OpenVINO, ORT-C++, and TensorRT
    models.

    ``model_path`` additionally accepts a ``backend:path`` spec:
    ``openvino:models/yolov8s_openvino.xml`` or ``openvino_int8:models/...
    ``. Both prefixes load the same :class:`~src.openvino_engine.OpenVINOEngine`
    (the precision is opaque to the wrapper — the ``_int8`` alias exists so
    the two precision variants stay visually distinct in commands). The
    plain ``.pt`` / ``.pth`` / ``.onnx`` forms are unchanged.

    An ``ort_cpp:<onnx_path>`` prefix selects the C++ ORT backend: no in-process
    session is loaded; ``forward`` shells out to the built ``ort_cpp``
    exe in ``--dump-raw-dir`` mode, which re-letterboxes from the image paths
    and writes raw pre-NMS forward tensors.
    This is the **full-pipeline** consistency path — the C++ preprocess
    (``cpp/common/letterbox.cpp``) is exercised alongside the forward, so the
    comparison validates the C++ mirror of the Python preprocess+forward
    end-to-end.

    A ``tensorrt:<engine_path>`` prefix selects the TensorRT backend: the
    ``.engine`` is deserialized lazily on the first forward (no in-process
    engine at construction); ``forward`` runs the pre-NMS raw output through
    :meth:`TensorRTEngine.raw_forward`.
    """

    # Prefixes that route to OpenVINOEngine (both alias the same engine).
    OPENVINO_PREFIXES = ("openvino_int8:", "openvino:")

    # Backend selector for the C++ ORT backend (mirrors benchmark's label).
    ORT_CPP_PREFIX = "ort_cpp:"

    # Backend selector for the TensorRT backend (mirrors benchmark's label).
    TENSORRT_PREFIX = "tensorrt:"

    def __init__(self, model_path: str, device: str) -> None:
        spec = str(model_path)
        self.device = (
            "cuda" if device == "cuda" and torch.cuda.is_available() else "cpu"
        )
        # TRT engine GPU id: a numeric --device (e.g. "1") selects that GPU for
        # the TensorRTEngine; "cpu"/"cuda" -> GPU 0 (the TRT engine always runs
        # on GPU). Stored separately from self.device (the "cpu"/"cuda" mode the
        # ORT reference + preprocess use) so those paths are unchanged by a
        # numeric --device.
        if isinstance(device, int) and not isinstance(device, bool):
            self._trt_gpu_id = device
        elif isinstance(device, str) and device.isdigit():
            self._trt_gpu_id = int(device)
        else:
            self._trt_gpu_id = 0
        if spec.startswith(self.ORT_CPP_PREFIX):
            # C++ backend: the model file is the part after the prefix; the exe
            # is resolved lazily so a wrapper can be constructed without a
            # built exe (e.g. the test suite) — only an actual forward call
            # resolves it and may raise the "build it first" error.
            self.type = "ort_cpp"
            self.path = spec[len(self.ORT_CPP_PREFIX):]
            self.model_path = self.path
            self.model = None
            self._exe = None
            return
        if spec.startswith(self.TENSORRT_PREFIX):
            # TensorRT backend: the engine is deserialized lazily on the first
            # forward call (the same lazy contract as ort_cpp:) — constructing
            # the wrapper without TRT installed / without the .engine staged
            # does not fail; only an actual forward call resolves it.
            self.type = "tensorrt"
            self.path = spec[len(self.TENSORRT_PREFIX):]
            self.model_path = self.path
            self.model = None
            return
        self.openvino_backend: Optional[str] = None
        for prefix in self.OPENVINO_PREFIXES:
            if spec.startswith(prefix):
                # Strip exactly ``len(prefix)`` characters from the head of
                # the spec; the path text is preserved verbatim.
                self.openvino_backend = spec[len(prefix):]
                break
        # The full spec (with prefix) is not preserved anywhere downstream.
        # ``is not None``, not truthiness: a bare "openvino:" (empty path)
        # must keep the empty stripped path — falling back to the prefixed
        # spec would put the prefix back into every downstream path check.
        self.path = spec if self.openvino_backend is None else self.openvino_backend
        if self.openvino_backend is not None:
            self.type = "openvino"
        else:
            suffix = Path(self.path).suffix.lower()
            self.type = "pt" if suffix in (".pt", ".pth") else "onnx"
        self.model = self._load_model()

    def _load_model(self):
        if self.type == "openvino":
            if not Path(self.path).exists():
                raise FileNotFoundError(f"Model file not found: {self.path}")
            # Fail fast on a wrong suffix before the heavy import: a
            # non-.xml path raises PathValidationError naming the actual
            # path, ahead of the lazy engine import.
            if Path(self.path).suffix.lower() != ".xml":
                raise PathValidationError(
                    f"openvino backend expects an OpenVINO IR (.xml), "
                    f"got: {self.path}"
                )
            # Deferred: OpenVINOEngine is an optional dependency
            # (requirements-openvino.txt) and pulls the full engine stack;
            # keeping it inside the openvino branch lets PT/ONNX
            # consistency runs proceed without openvino installed.
            from .openvino_engine import OpenVINOEngine

            # OpenVINO consumes host numpy, so the CUDA-or-CPU torch device
            # does not apply here: the device comes from the
            # ``OPENVINO_DEVICE`` env var (default CPU) via the engine's own
            # preflight, and the resolved value is recorded below so the
            # report can state what actually ran.
            requested = os.environ.get("OPENVINO_DEVICE", "CPU")
            engine = OpenVINOEngine(model_path=self.path, device=requested)
            self.openvino_device = {
                "requested_device": requested.upper(),
                "actual_device": engine.device,
            }
            logger.info(
                "OpenVINO model loaded: %s | requested_device=%s | "
                "actual_device=%s",
                self.path, requested.upper(), engine.device,
            )
            return engine

        if not Path(self.path).exists():
            raise FileNotFoundError(f"Model file not found: {self.path}")

        # Suffix gate: existing_validation accepts .xml/.bin for the openvino
        # command group and .engine for the tensorrt command group, so a
        # mispointed --model1/--model2 can reach this wrapper with a suffix
        # its loader cannot read. Reject it ahead of the YOLO()/ORT load,
        # with the owning prefix named.
        if Path(self.path).suffix.lower() not in (".pt", ".pth", ".onnx"):
            raise PathValidationError(
                f"consistency expects a .pt/.pth checkpoint or an ONNX file, "
                f"got: {self.path}. OpenVINO IR files (.xml/.bin) are served "
                f"through the openvino:/openvino_int8: prefixes, TensorRT "
                f"engines (.engine) through the tensorrt: prefix."
            )

        try:
            if self.type == "pt":
                m = YOLO(self.path)
                m.to(self.device)
                m.model.eval()
                logger.info("PyTorch model loaded: %s", self.path)
                return m
            session = get_ort_session(self.path, self.device)
            logger.info("ONNX model loaded: %s", self.path)
            return session
        except Exception as e:
            logger.exception("Model load failed [%s]: %s", self.type, self.path)
            raise RuntimeError(f"Cannot load model {self.path}") from e

    def forward(
        self, x: torch.Tensor, paths: Optional[List] = None,
        imgsz: Optional[int] = None,
    ) -> np.ndarray:
        """Run a forward pass and return the raw pre-NMS output as numpy.

        ``paths`` is only used by the ``ort_cpp`` backend (it re-preprocesses
        from the image files); ``imgsz`` sizes the ort_cpp re-preprocess and
        the TensorRT engine construction. The other backends consume the
        already-preprocessed tensor ``x`` and ignore both.
        """
        if self.type == "ort_cpp":
            return self._forward_ort_cpp(paths or [], imgsz or 640)
        if self.type == "tensorrt":
            # Deserialize the .engine on first forward, then reuse. TRT
            # consumes the already-preprocessed tensor ``x`` like the onnx
            # path.
            if self.model is None:
                from . import TensorRTEngine, tensorrt_available
                if not tensorrt_available():
                    raise ImportError(
                        "tensorrt is not installed. Run: "
                        "pip install -r requirements-tensorrt.txt"
                    )
                self.model = TensorRTEngine(
                    model_path=self.model_path, device=self._trt_gpu_id,
                    imgsz=imgsz or 640,
                )
            # _forward raises above the engine's max_batch: the batch is
            # capped at that count and sub-looped here.
            return trt_forward_capped(self.model, x.detach().cpu().numpy())
        if self.type == "openvino":
            # OpenVINO consumes host numpy: the torch CUDA tensor is copied
            # to host before the forward (a --device cuda run with an
            # OpenVINO model is a cross-device comparison; the host copy is
            # part of that path's contract).
            batch = x.detach().cpu().numpy().astype(np.float32)
            return self.model._forward(batch)
        if self.type == "pt":
            return pt_forward(self.model, x)
        return ort_forward(self.model, x, self.device)

    def release(self) -> None:
        """Release backend resources that need explicit teardown.

        Only the TensorRT backend holds one — the lazily deserialized
        ``.engine`` (its stream, device buffers, and the retained primary
        context), torn down through the engine's idempotent ``release()``.
        Safe on a wrapper that never ran a forward (``model`` is still
        ``None``) and on every other backend: the PT / ONNX / ort_cpp
        resources release through GC or process exit, and OpenVINO holds no
        explicit device handles.
        """
        if self.type == "tensorrt" and self.model is not None:
            release = getattr(self.model, "release", None)
            if callable(release):
                release()
            self.model = None

    def _forward_ort_cpp(self, paths: List, imgsz: int) -> np.ndarray:
        """Shell out to ``ort_cpp --dump-raw-dir`` for the batch, return stacked
        ``(bs, C, N)`` raw forward tensors.

        One spawn per batch (the C++ side loads the session once per call).
        Images are staged into a temp in-dir with zero-padded names so the
        C++ ``--dir`` loader's sort order matches the batch order; outputs are
        loaded back in sorted stem order. Suffixes outside
        ``ORT_CPP_IMAGE_SUFFIXES`` are rejected at staging time (the same
        contract as the benchmark's ``_run_ort_cpp`` — the C++ loader would
        silently drop them). The C++ session's thread knobs come
        from the same ``_thread_knobs()`` values the Python benchmark sessions
        use; the Python comparison session itself is built without
        ``SessionOptions`` (ORT defaults), so the two sides do not share one
        operator-scheduling/reduction order (see docs/ORT_CPP.md).
        """
        if not paths:
            raise RuntimeError("ort_cpp forward requires image paths")
        for p in paths:
            ext = Path(str(p)).suffix or ".jpg"
            if ext.lower() not in ORT_CPP_IMAGE_SUFFIXES:
                raise RuntimeError(
                    f"ort_cpp backend requires .jpg/.jpeg/.png/.bmp images, "
                    f"got '{ext}': {p}"
                )
        if self._exe is None:
            self._exe = resolve_ort_cpp_exe()

        n = len(paths)
        width = max(6, len(str(n - 1)))
        tmp_in = tempfile.mkdtemp(prefix="ort_cpp_cons_in_")
        tmp_out = tempfile.mkdtemp(prefix="ort_cpp_cons_out_")
        try:
            for i, p in enumerate(paths):
                ext = Path(str(p)).suffix or ".jpg"
                shutil.copyfile(str(p), os.path.join(tmp_in, f"{i:0{width}d}{ext}"))

            intra, inter = _thread_knobs()
            cmd = [
                self._exe,
                "--dump-raw-dir", tmp_out,
                "--dir", tmp_in,
                "-m", self.model_path,
                "--imgsz", str(imgsz),
                "--intra-op-threads", str(intra),
                "--inter-op-threads", str(inter),
            ]
            # Fixed 600 s timeout: a hung exe (stale build, deadlocked
            # session) fails the run at the cap. The dump is one forward
            # pass per staged image; the margin covers model load and
            # first-run graph optimization.
            proc = subprocess.run(
                cmd, capture_output=True, text=True, timeout=600
            )
            if proc.returncode != 0:
                raise RuntimeError(
                    f"ort_cpp --dump-raw-dir failed (exit {proc.returncode}):\n"
                    f"stderr: {proc.stderr[-2000:]}"
                )

            npys = sorted(Path(tmp_out).glob("*.npy"))
            if len(npys) != n:
                raise RuntimeError(
                    f"ort_cpp produced {len(npys)} .npy files, expected {n}"
                )
            # Each .npy is (1, C, N); concatenate along axis 0 → (bs, C, N) to
            # match the Python ort_forward output shape for the same batch.
            outs = [np.load(str(p)) for p in npys]
            return np.concatenate(outs, axis=0)
        finally:
            shutil.rmtree(tmp_in, ignore_errors=True)
            shutil.rmtree(tmp_out, ignore_errors=True)


